const AUDIENCE: &str = "guard-idp-test";
const ALLOWED_RESULT: &str = r#"{"jsonrpc":"2.0","id":1,"result":{"content":[]}}"#;

/// One provider token shape.
struct Case {
    /// Also the upstream path segment, so each case counts its own backend hits.
    name: &'static str,
    port: Port,
    caller_attributes: &'static str,
    separator: Option<&'static str>,
    granted: &'static str,
    /// Claims that carry the granted value.
    matching: Value,
    /// The same claim with other values only.
    other: Value,
}

