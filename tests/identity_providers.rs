struct SigningKey {
    dir: std::path::PathBuf,
    public_pem: String,
}

impl SigningKey {
    fn generate() -> Self {
        Self::generate_named("signing")
    }

    fn generate_named(name: &str) -> Self {
        let dir = std::env::temp_dir().join(format!("guard-idp-{}-{name}", std::process::id()));
        std::fs::create_dir_all(&dir).unwrap();
        let private = dir.join("private.pem");
        let public = dir.join("public.pem");
        run(
            "openssl",
            &["genrsa", "-out", private.to_str().unwrap(), "2048"],
        );
        run(
            "openssl",
            &[
                "rsa",
                "-in",
                private.to_str().unwrap(),
                "-pubout",
                "-out",
                public.to_str().unwrap(),
            ],
        );
        let public_pem = std::fs::read_to_string(&public).unwrap();
        Self { dir, public_pem }
    }

    fn sign(&self, claims: &Value) -> String {
        let header = URL_SAFE_NO_PAD.encode(json!({"alg": "RS256", "typ": "JWT"}).to_string());
        let payload = URL_SAFE_NO_PAD.encode(claims.to_string());
        let input = format!("{header}.{payload}");
        let input_file = self.dir.join("input");
        std::fs::write(&input_file, &input).unwrap();
        let output = Command::new("openssl")
            .args(["dgst", "-sha256", "-sign"])
            .arg(self.dir.join("private.pem"))
            .arg(&input_file)
            .output()
            .unwrap();
        assert!(output.status.success(), "openssl dgst failed");
        format!("{input}.{}", URL_SAFE_NO_PAD.encode(output.stdout))
    }
}

impl Drop for SigningKey {
    fn drop(&mut self) {
        let _ = std::fs::remove_dir_all(&self.dir);
    }
}

fn run(program: &str, args: &[&str]) {
    let output = Command::new(program).args(args).output().unwrap();
    assert!(
        output.status.success(),
        "{program} {args:?} failed: {}",
        String::from_utf8_lossy(&output.stderr)
    );
}

fn now() -> u64 {
    std::time::SystemTime::now()
        .duration_since(std::time::UNIX_EPOCH)
        .unwrap()
        .as_secs()
}

fn call(tool: &str) -> String {
    json!({"jsonrpc": "2.0", "id": 1, "method": "tools/call", "params": {"name": tool, "arguments": {}}}).to_string()
}

fn jwt_validation(public_pem: &str) -> PolicyConfig {
    // Same settings as the Connected gateway check, with a static key.
    PolicyConfig::builder()
        .name("jwt-validation-flex")
        .configuration(json!({
            "jwtOrigin": "httpBearerAuthenticationHeader",
            "jwtExpression": "#[attributes.headers['jwt']]",
            "signingMethod": "rsa",
            "signingKeyLength": 256,
            "jwtKeyOrigin": "text",
            "textKey": public_pem,
            "customKeyExpression": "#[authentication.properties['key_to_your_public_pem_certificate']]",
            "jwksUrl": "http://your-jwks-service.example:80/base/path",
            "jwksServiceTimeToLive": 60,
            "jwksServiceConnectionTimeout": 10000,
            "skipClientIdValidation": true,
            "clientIdExpression": "#[vars.claimSet.client_id]",
            "validateAudClaim": true,
            "mandatoryAudClaim": true,
            "supportedAudiences": AUDIENCE,
            "mandatoryExpClaim": true,
            "mandatoryNbfClaim": false,
            "validateCustomClaim": false
        }))
        .build()
}

fn guard(case: &Case) -> PolicyConfig {
    let mut config = json!({
        "callerAttributes": case.caller_attributes,
        "grants": [{"attribute": case.granted, "level": "write"}],
        "toolOverrides": [{"name": "update_ticket", "class": "write"}]
    });
    if let Some(separator) = case.separator {
        config["callerAttributeSeparator"] = json!(separator);
    }
    PolicyConfig::builder()
        .name(POLICY_NAME)
        .configuration(config)
        .build()
}

/// Valid registered claims plus the provider-specific ones.
fn claims(extra: &Value) -> Value {
    let mut claims =
        json!({"iss": "https://idp.example", "sub": "user-1", "aud": AUDIENCE, "exp": now() + 600});
    for (k, v) in extra.as_object().unwrap() {
        claims[k] = v.clone();
    }
    claims
}

async fn send(
    client: &reqwest::Client,
    url: &str,
    token: Option<&str>,
) -> anyhow::Result<(u16, Value)> {
    let mut request = client
        .post(url)
        .header("content-type", "application/json")
        .header("accept", "application/json, text/event-stream")
        .body(call("update_ticket"));
    if let Some(token) = token {
        request = request.header("authorization", format!("Bearer {token}"));
    }
    let response = request.send().await?;
    let status = response.status().as_u16();
    let body = serde_json::from_str(&response.text().await?).unwrap_or(Value::Null);
    Ok((status, body))
}

/// The gateway reports ready before every listener is up when it loads many
/// APIs, so wait until this one accepts connections.
async fn wait_for_listener(client: &reqwest::Client, url: &str) {
    for _ in 0..50 {
        if client.get(url).send().await.is_ok() {
            return;
        }
        tokio::time::sleep(std::time::Duration::from_millis(200)).await;
    }
    panic!("listener {} never came up", url);
}

#[pdk_test]
async fn identity_provider_token_shapes() -> anyhow::Result<()> {
    let key = SigningKey::generate();
    let other_key = SigningKey::generate_named("other");
    let cases = cases();

    let httpmock_config = HttpMockConfig::builder()
        .port(80)
        .version("latest")
        .hostname("backend")
        .build();

    let mut flex_builder = FlexConfig::builder()
        .version(flex_version())
        .hostname("local-flex")
        .config_mounts([(POLICY_DIR, "policy"), (COMMON_CONFIG_DIR, "common")]);
    for case in &cases {
        let api = ApiConfig::builder()
            .name(case.name)
            .upstream(&httpmock_config)
            .path(format!("/{}/", case.name))
            .port(case.port)
            .policies([jwt_validation(&key.public_pem), guard(case)])
            .build();
        flex_builder = flex_builder.with_api(api);
    }

    let composite = TestComposite::builder()
        .with_service(flex_builder.build())
        .with_service(httpmock_config)
        .build()
        .await?;
    let flex: Flex = composite.service()?;
    let httpmock: HttpMock = composite.service()?;
    let mock_server = MockServer::connect_async(httpmock.socket()).await;
    let client = reqwest::Client::new();

    for case in &cases {
        let url = format!("{}/mcp", flex.external_url(case.port).unwrap());
        wait_for_listener(&client, &url).await;
        let backend = mock_server
            .mock_async(|when, then| {
                when.method(POST).path_contains(format!("/{}/", case.name));
                then.status(200)
                    .header("content-type", "application/json")
                    .body(ALLOWED_RESULT);
            })
            .await;

        // Granted value: raised to write, forwarded.
        let (status, body) = send(&client, &url, Some(&key.sign(&claims(&case.matching)))).await?;
        assert_eq!(status, 200, "{}: granted token", case.name);
        assert!(
            body.get("result").is_some(),
            "{}: granted token not forwarded: {body}",
            case.name
        );
        assert_eq!(
            backend.hits_async().await,
            1,
            "{}: granted token",
            case.name
        );

        // Same claim, other values: stays at read, refused before the backend.
        let (status, body) = send(&client, &url, Some(&key.sign(&claims(&case.other)))).await?;
        assert_eq!(status, 200, "{}: other token", case.name);
        assert_eq!(
            body.pointer("/error/data/reason"),
            Some(&json!("level_insufficient")),
            "{}: {body}",
            case.name
        );
        assert_eq!(
            body.pointer("/error/data/callerLevel"),
            Some(&json!("read")),
            "{}: {body}",
            case.name
        );
        assert_eq!(
            backend.hits_async().await,
            1,
            "{}: other token reached the backend",
            case.name
        );

        backend.delete_async().await;
    }

    // JWT Validation refuses unverified tokens before the guard runs.
    let first = &cases[0];
    let url = format!("{}/mcp", flex.external_url(first.port).unwrap());
    let backend = mock_server
        .mock_async(|when, then| {
            when.method(POST).path_contains(format!("/{}/", first.name));
            then.status(200)
                .header("content-type", "application/json")
                .body(ALLOWED_RESULT);
        })
        .await;
    let expired = {
        let mut c = claims(&first.matching);
        c["exp"] = json!(now() - 600);
        key.sign(&c)
    };
    let wrong_audience = {
        let mut c = claims(&first.matching);
        c["aud"] = json!("another-api");
        key.sign(&c)
    };
    let unverified = [
        ("no token", None),
        ("wrong key", Some(other_key.sign(&claims(&first.matching)))),
        ("expired", Some(expired)),
        ("wrong audience", Some(wrong_audience)),
    ];
    for (label, token) in &unverified {
        let (status, body) = send(&client, &url, token.as_deref()).await?;
        assert!(
            (400..500).contains(&status),
            "{}: expected a 4xx from JWT Validation, got {} {}",
            label,
            status,
            body
        );
        assert!(
            body.get("jsonrpc").is_none(),
            "{}: the guard answered: {}",
            label,
            body
        );
    }
    assert_eq!(
        backend.hits_async().await,
        0,
        "an unverified token reached the backend"
    );

    Ok(())
}
