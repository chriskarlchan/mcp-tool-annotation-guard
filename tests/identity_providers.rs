//! Identity-provider token shapes (docs/configuration.md, "Caller attributes").
//!
//! The guard is IdP-neutral: it reads claims that the built-in JWT Validation
//! policy has already verified. Providers differ only in where they put roles,
//! groups and scopes, and in whether the claim is an array or a space-separated
//! string. Each case below mimics one provider's token shape, runs it through
//! JWT Validation and then the guard on a local gateway, and checks that:
//!
//! - a token carrying the granted value raises the caller to `write`, so a write
//!   tool is forwarded to the backend;
//! - a token with the same claim but another value stays at `read`, so the call
//!   is refused and never reaches the backend.
//!
//! JWT Validation negatives (no token, wrong key, expired, wrong audience)
//! show that the guard never sees an unverified token.
//!
//! Tokens are signed at test time with an RSA key generated by the openssl CLI,
//! so no private key is committed. This proves token *shapes*; it does not call
//! the providers themselves.

